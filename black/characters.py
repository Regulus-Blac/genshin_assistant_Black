"""Stage characters and their selectable looks.

The manifest in ``assets/gallery.json`` is generated by
``tools/build_gallery.py``.  Each character owns a small list of full-stage
illustrations; the app only needs to load a static image for the selected look.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from .paths import ASSETS, IMAGES

DEFAULT_CHARACTER_ID = "vodyanitsa"
DEFAULT_LOOK_ID = "window"

_FALLBACK = {
    "version": 1,
    "characters": [
        {
            "id": "vodyanitsa",
            "name": "沃雅妮莎",
            "title": "潮声中的歌者",
            "element": "hydro",
            "color": "#7fd3d1",
            "looks": [
                {"id": "window", "label": "窗边", "orientation": "portrait", "art": "gallery/vody_window_portrait.jpg", "thumb": "gallery/thumbs/vody_window.jpg"},
                {"id": "qipao_half", "label": "旗袍·半身", "orientation": "portrait", "art": "gallery/vody_qipao_half_portrait.jpg", "thumb": "gallery/thumbs/vody_qipao_half.jpg"},
                {"id": "snowpool", "label": "雪糕水池", "orientation": "landscape", "art": "gallery/vody_snowpool_wide.jpg", "thumb": "gallery/thumbs/vody_snowpool.jpg"},
            ],
            "default_look": "window",
        }
    ],
}


@lru_cache(maxsize=1)
def _manifest() -> dict:
    path = ASSETS / "gallery.json"
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            if data.get("characters"):
                return data
        except Exception:
            pass
    return _FALLBACK


@lru_cache(maxsize=1)
def _by_id() -> dict[str, dict]:
    return {c["id"]: c for c in _manifest().get("characters", [])}


def all_characters() -> list[dict]:
    return list(_manifest().get("characters", []))


def get_character(character_id: str | None) -> dict:
    chars = _by_id()
    cid = str(character_id or "")
    # Older builds used a few shortened IDs.
    aliases = {"raiden_shogun": "raiden", "yae_miko": "yae", "hu_tao": "hutao"}
    cid = aliases.get(cid, cid)
    return chars.get(cid) or chars.get(DEFAULT_CHARACTER_ID) or _FALLBACK["characters"][0]


def default_look(meta: dict) -> dict:
    looks = meta.get("looks") or []
    if not looks:
        return {"id": "default", "label": "默认", "art": "art_snow.jpg", "thumb": "art_snow.jpg"}
    wanted = meta.get("default_look")
    for look in looks:
        if look.get("id") == wanted:
            return look
    return looks[0]


def get_look(meta: dict, look_id: str | None = None) -> dict:
    for look in meta.get("looks", []):
        if look.get("id") == look_id:
            return look
    return default_look(meta)


def legacy_look_id(character_id: str, art_name: str | None) -> str | None:
    """Map the pre-gallery ``art`` setting to a look id."""
    mapping = {
        "art_snow.jpg": "window",
        "art_wisteria.jpg": "window",
        "art_picnic.jpg": "window",
        "art_tea.jpg": "window",
    }
    if character_id == DEFAULT_CHARACTER_ID:
        return mapping.get(str(art_name or ""), "window")
    return None


def character_count() -> int:
    return len(_manifest().get("characters", []))


def look_count() -> int:
    return sum(len(c.get("looks", [])) for c in _manifest().get("characters", []))


def art_path(relative: str) -> Path:
    return IMAGES / relative
